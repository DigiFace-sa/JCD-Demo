#!/usr/bin/env node
/**
 * Official image pipeline: assets/official-images.json → public/images/jcdc + src/data/officialImages.ts
 *
 * For every official JCDC render in the manifest:
 *  - fetch the original into .cache/official/ (gitignored) unless it is already cached;
 *  - write AVIF at 1280 / 1920 / 2560 px wide (never upscaled), the primary format;
 *  - write one WebP at ≤1920 px as `<id>.webp`, the fallback (and the path legacy pages use).
 * Then it regenerates the typed size table used by components.
 *
 *   npm run images            incremental (skips outputs newer than their original)
 *   npm run images -- --force re-encode everything
 */
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'assets/official-images.json');
const CACHE = join(ROOT, '.cache/official');
const OUT = join(ROOT, 'public/images/jcdc');
const TABLE = join(ROOT, 'src/data/officialImages.ts');

const WIDTHS = [1280, 1920, 2560];
const FALLBACK_WIDTH = 1920;
/** Visually transparent for architectural renders at a fraction of WebP's size. */
const AVIF = { quality: 52, effort: 5, chromaSubsampling: '4:2:0' };
const WEBP = { quality: 80, effort: 5 };

const force = process.argv.includes('--force');
const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
mkdirSync(CACHE, { recursive: true });
mkdirSync(OUT, { recursive: true });

async function original(image) {
  const file = join(CACHE, image.id);
  if (!existsSync(file)) {
    process.stdout.write(`  downloading ${image.id}… `);
    const response = await fetch(image.url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
    if (!response.ok) throw new Error(`${image.id}: HTTP ${response.status}`);
    writeFileSync(file, Buffer.from(await response.arrayBuffer()));
    console.log('done');
  }
  return file;
}

const fresh = (output, source) =>
  !force && existsSync(output) && statSync(output).mtimeMs >= statSync(source).mtimeMs;

const table = {};
let written = 0;
for (const image of manifest.images) {
  const source = await original(image);
  const { width, height } = await sharp(source).metadata();
  // Standard steps below the original, plus the original itself when it falls between steps.
  const widths = WIDTHS.filter((w) => w <= width);
  if (width < WIDTHS[WIDTHS.length - 1] && !widths.includes(width)) widths.push(width);
  for (const w of widths) {
    const output = join(OUT, `${image.id}-${w}.avif`);
    if (fresh(output, source)) continue;
    await sharp(source).resize({ width: w, withoutEnlargement: true }).avif(AVIF).toFile(output);
    written++;
  }
  const fallbackWidth = Math.min(FALLBACK_WIDTH, width);
  const fallback = join(OUT, `${image.id}.webp`);
  if (!fresh(fallback, source)) {
    await sharp(source).resize({ width: fallbackWidth, withoutEnlargement: true }).webp(WEBP).toFile(fallback);
    written++;
  }
  table[image.id] = {
    width: fallbackWidth,
    height: Math.round((fallbackWidth * height) / width),
    widths,
  };
  console.log(`${image.id.padEnd(22)} ${width}×${height} → ${widths.join('/')} avif + ${fallbackWidth} webp`);
}

const body = Object.entries(table)
  .map(
    ([id, { width, height, widths }]) =>
      `  '${id}': { width: ${width}, height: ${height}, widths: [${widths.join(', ')}] },`,
  )
  .join('\n');
writeFileSync(
  TABLE,
  `// Generated by scripts/images.mjs from assets/official-images.json. Do not edit by hand.
// width/height: the WebP fallback (aspect ratio for layout); widths: AVIF sizes on disk.

export const OFFICIAL_IMAGES = {
${body}
} as const;

export type OfficialImage = keyof typeof OFFICIAL_IMAGES;
`,
);
console.log(`\n${manifest.images.length} images, ${written} files written → public/images/jcdc, src/data/officialImages.ts`);
